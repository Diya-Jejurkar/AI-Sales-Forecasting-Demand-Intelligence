# =========================================================
# LOAD DATA
# =========================================================

@st.cache_data
def load_data():
    df = pd.read_csv("AI_Sales_Forecasting_10000_Rows.csv")
    df["Order_Date"] = pd.to_datetime(df["Order_Date"])
    return df


df = load_data()

# =========================================================
# HEADER
# =========================================================

st.title("AI Sales Forecasting & Demand Intelligence")
st.markdown(
    "An AI-powered dashboard for analyzing historical sales "
    "and forecasting future demand."
)

st.divider()

# =========================================================
# SIDEBAR FILTERS
# =========================================================

st.sidebar.header("Dashboard Filters")

categories = st.sidebar.multiselect(
    "Select Category",
    options=sorted(df["Category"].unique()),
    default=sorted(df["Category"].unique())
)

regions = st.sidebar.multiselect(
    "Select Region",
    options=sorted(df["Region"].unique()),
    default=sorted(df["Region"].unique())
)

channels = st.sidebar.multiselect(
    "Select Sales Channel",
    options=sorted(df["Sales_Channel"].unique()),
    default=sorted(df["Sales_Channel"].unique())
)

filtered_df = df[
    (df["Category"].isin(categories)) &
    (df["Region"].isin(regions)) &
    (df["Sales_Channel"].isin(channels))
].copy()

# =========================================================
# KPI CALCULATIONS
# =========================================================

total_revenue = filtered_df["Revenue"].sum()

total_orders = filtered_df["Order_ID"].nunique()

total_quantity = filtered_df["Quantity"].sum()

average_order_value = (
    total_revenue / total_orders
    if total_orders > 0
    else 0
)

# =========================================================
# KPI CARDS
# =========================================================

col1, col2, col3, col4 = st.columns(4)

col1.metric(
    "Total Revenue",
    f"₹{total_revenue:,.0f}"
)

col2.metric(
    "Total Orders",
    f"{total_orders:,}"
)

col3.metric(
    "Units Sold",
    f"{total_quantity:,}"
)

col4.metric(
    "Average Order Value",
    f"₹{average_order_value:,.0f}"
)

st.divider()

# =========================================================
# MONTHLY SALES
# =========================================================

monthly_sales = (
    filtered_df
    .groupby(filtered_df["Order_Date"].dt.to_period("M"))["Revenue"]
    .sum()
    .reset_index()
)

monthly_sales["Order_Date"] = monthly_sales["Order_Date"].dt.to_timestamp()

monthly_sales.columns = ["Month", "Revenue"]

# =========================================================
# SALES TREND
# =========================================================

st.subheader("📈 Historical Sales Trend")

fig_sales = px.line(
    monthly_sales,
    x="Month",
    y="Revenue",
    markers=True,
    title="Monthly Revenue Trend"
)

fig_sales.update_layout(
    xaxis_title="Month",
    yaxis_title="Revenue",
    hovermode="x unified"
)

st.plotly_chart(
    fig_sales,
    use_container_width=True
)

# =========================================================
# AI FORECAST
# =========================================================

st.subheader("🤖 AI Revenue Forecast")

# Load the final forecast generated by the forecasting model
try:
    future_df = pd.read_csv(
        "AI_Sales_Monthly_Forecast_2026.csv"
    )

    future_df["Month"] = pd.to_datetime(
        future_df["Forecast_Month"]
    )

    future_df["Forecast"] = future_df["Revenue"]

except Exception as e:
    st.error(
        "Forecast file could not be loaded. "
        "Make sure AI_Sales_Monthly_Forecast_2026.csv "
        "is present in the project folder."
    )
    st.stop()


# =========================================================
# FORECAST CHART
# =========================================================

st.markdown("### 📈 Historical Sales vs AI Forecast")

historical_plot = monthly_sales[
    ["Month", "Revenue"]
].copy()

historical_plot["Type"] = "Historical Revenue"

forecast_plot = future_df[
    ["Month", "Forecast"]
].copy()

forecast_plot = forecast_plot.rename(
    columns={"Forecast": "Revenue"}
)

forecast_plot["Type"] = "AI Forecast"

combined_plot = pd.concat(
    [historical_plot, forecast_plot],
    ignore_index=True
)

fig_forecast = px.line(
    combined_plot,
    x="Month",
    y="Revenue",
    color="Type",
    markers=True,
    title="Monthly Revenue: Historical vs AI Forecast"
)

fig_forecast.update_layout(
    xaxis_title="",
    yaxis_title="Revenue (₹)",
    hovermode="x unified",
    legend_title="",
    margin=dict(
        l=20,
        r=20,
        t=60,
        b=20
    )
)

fig_forecast.update_traces(
    line=dict(width=3),
    marker=dict(size=6)
)

st.plotly_chart(
    fig_forecast,
    use_container_width=True
)

# =========================================================
# FORECAST KPIs
# =========================================================

total_forecast = future_df["Forecast"].sum()

average_forecast = future_df["Forecast"].mean()

highest_forecast = future_df["Forecast"].max()

lowest_forecast = future_df["Forecast"].min()

highest_forecast_month = (
    future_df.loc[
        future_df["Forecast"].idxmax(),
        "Month"
    ].strftime("%B %Y")
)


forecast_col1, forecast_col2, forecast_col3, forecast_col4 = st.columns(4)

forecast_col1.metric(
    "6-Month Forecast",
    f"₹{total_forecast:,.0f}"
)

forecast_col2.metric(
    "Average Monthly",
    f"₹{average_forecast:,.0f}"
)

forecast_col3.metric(
    "Highest Forecast",
    f"₹{highest_forecast:,.0f}"
)

forecast_col4.metric(
    "Peak Forecast Month",
    highest_forecast_month
)


# =========================================================
# DEMAND STATUS
# =========================================================

historical_average = monthly_sales["Revenue"].mean()


def demand_status(value):

    if value >= historical_average * 1.10:
        return "High Demand"

    elif value <= historical_average * 0.90:
        return "Low Demand"

    else:
        return "Medium Demand"


future_df["Demand Status"] = (
    future_df["Forecast"]
    .apply(demand_status)
)


# =========================================================
# FORECAST TABLE
# =========================================================

st.subheader("🔮 Six-Month Demand Forecast")

display_forecast = future_df[
    ["Month", "Forecast", "Demand Status"]
].copy()

display_forecast["Month"] = (
    display_forecast["Month"]
    .dt.strftime("%B %Y")
)

display_forecast["Forecast"] = (
    display_forecast["Forecast"]
    .round(0)
)

st.dataframe(
    display_forecast,
    use_container_width=True,
    hide_index=True
)


# =========================================================
# DEMAND STATUS CHART
# =========================================================

